import { DeviceConfig, CalculatedTelemetry } from '../types';

export function calculateTelemetry(
  pulseCount: number,
  analogSensorValue: number,
  config: DeviceConfig
): CalculatedTelemetry {
  // 1. Distance calculation
  const distanceMeters = pulseCount * config.wheelCircumference;
  const distanceKm = distanceMeters / 1000.0;

  // 2. Fuel sensor reading (analogRead 0-1023)
  // Invert sensor if float arm is wired inverted
  const effectiveAdc = config.invertFuelSensor
    ? 1023 - analogSensorValue
    : analogSensorValue;

  // Arduino map function: (x - in_min) * (out_max - out_min) / (in_max - in_min) + out_min
  const fuelPercent = Math.max(0, Math.min(100, Math.round((effectiveAdc * 100) / 1023)));
  const fuelLevelLiters = (fuelPercent / 100.0) * config.fuelCapacity;
  const fuelConsumedLiters = Math.max(0, config.fuelCapacity - fuelLevelLiters);

  // 3. Mileage calculation exactly per Arduino code:
  // if (fuelLevel > 0) { mileage = distanceKm / (fuelCapacity - fuelLevel + 0.01); } else { mileage = 0; }
  let mileageKmPerL = 0;
  if (fuelLevelLiters > 0) {
    mileageKmPerL = distanceKm / (config.fuelCapacity - fuelLevelLiters + 0.01);
  } else {
    mileageKmPerL = 0;
  }

  // Common conversions
  // 1 km/L = 2.35214583 US MPG
  const mileageMpgUs = mileageKmPerL * 2.35214583;
  // L/100km = 100 / (km/L)
  const mileageLPer100Km = mileageKmPerL > 0 ? 100 / mileageKmPerL : 0;

  // Estimated range based on current mileage & remaining fuel
  const estimatedRangeKm = mileageKmPerL > 0 ? fuelLevelLiters * mileageKmPerL : 0;

  // Analog voltage (0.00V - 5.00V)
  const analogVoltage = (analogSensorValue / 1023) * 5.0;

  // Format exactly like Arduino code:
  // lcd.print("Fuel:"); lcd.print(fuelPercent, 0); lcd.print("% "); lcd.print("L:"); lcd.print(fuelLevel, 1);
  const row0Str = `Fuel:${fuelPercent.toFixed(0)}% L:${fuelLevelLiters.toFixed(1)}`;
  // lcd.print("KM:"); lcd.print(distanceKm, 1);
  const row1Str = `KM:${distanceKm.toFixed(1)}`;

  // Serial monitor string:
  // Serial.print("Fuel: "); Serial.print(fuelPercent); Serial.print("% | Fuel Litres: "); Serial.print(fuelLevel);
  // Serial.print(" L | Distance: "); Serial.print(distanceKm); Serial.print(" KM | Mileage: "); Serial.print(mileage); Serial.println(" KM/L");
  const serialLine = `Fuel: ${fuelPercent}% | Fuel Litres: ${fuelLevelLiters.toFixed(1)} L | Distance: ${distanceKm.toFixed(1)} KM | Mileage: ${mileageKmPerL.toFixed(2)} KM/L`;

  return {
    distanceMeters,
    distanceKm,
    fuelPercent,
    fuelLevelLiters,
    fuelConsumedLiters,
    mileageKmPerL,
    mileageMpgUs,
    mileageLPer100Km,
    estimatedRangeKm,
    analogVoltage,
    lcdRow0: row0Str.padEnd(16, ' ').slice(0, 16),
    lcdRow1: row1Str.padEnd(16, ' ').slice(0, 16),
    serialLine,
  };
}

export function generateArduinoCode(config: DeviceConfig): string {
  return `/*
 * Smart Petrol Meter & Digital Trip Computer
 * IR Wheel Sensor (Pin 2 Interrupt) + Float Sensor (Pin A0) + 16x2 I2C LCD (${config.i2cAddress})
 * Auto-generated by Arduino Telemetry Lab
 */

#include <Wire.h>
#include <LiquidCrystal_I2C.h>

// Set the LCD address to ${config.i2cAddress} for a 16 chars and 2 line display
LiquidCrystal_I2C lcd(${config.i2cAddress}, 16, 2);

// Pin settings
const int irSensor = ${config.irPin};
const int fuelSensor = ${config.fuelPin};

// Variables
volatile unsigned long pulseCount = 0;
float wheelCircumference = ${config.wheelCircumference.toFixed(2)}; // meters
float distance = 0.0;
float fuelLevel = 0.0;
float mileage = 0.0;

// Vehicle tank capacity in litres
float fuelCapacity = ${config.fuelCapacity.toFixed(1)}; // litres

void countPulse()
{
  pulseCount++;
}

void setup()
{
  Serial.begin(9600);
  pinMode(irSensor, INPUT_PULLUP);
  attachInterrupt(
    digitalPinToInterrupt(irSensor),
    countPulse,
    FALLING
  );

  lcd.init();
  lcd.backlight();
  lcd.setCursor(0, 0);
  lcd.print("Petrol Meter");
  lcd.setCursor(0, 1);
  lcd.print("Starting...");
  delay(2000);
  lcd.clear();
}

void loop()
{
  // -------------------------
  // Distance calculation
  // -------------------------
  distance = pulseCount * wheelCircumference;
  // Convert meter to kilometer
  float distanceKm = distance / 1000.0;

  // -------------------------
  // Fuel sensor reading
  // -------------------------
  int sensorValue = analogRead(fuelSensor);
  ${
    config.invertFuelSensor
      ? '// Inverted sensor (1023 = empty, 0 = full)\n  sensorValue = 1023 - sensorValue;\n  '
      : ''
  }// Convert sensor value to percentage
  float fuelPercent = map(sensorValue, 0, 1023, 0, 100);
  fuelLevel = (fuelPercent / 100.0) * fuelCapacity;

  // -------------------------
  // Mileage calculation
  // (+0.01 prevents division by zero when tank is 100% full)
  // -------------------------
  if (fuelLevel > 0)
  {
    mileage = distanceKm / (fuelCapacity - fuelLevel + 0.01);
  }
  else
  {
    mileage = 0;
  }

  // -------------------------
  // LCD Display
  // -------------------------
  lcd.clear();
  lcd.setCursor(0, 0);
  lcd.print("Fuel:");
  lcd.print(fuelPercent, 0);
  lcd.print("% ");
  lcd.print("L:");
  lcd.print(fuelLevel, 1);

  lcd.setCursor(0, 1);
  lcd.print("KM:");
  lcd.print(distanceKm, 1);

  delay(${config.loopDelayMs});

  // -------------------------
  // Serial Monitor
  // -------------------------
  Serial.print("Fuel: ");
  Serial.print(fuelPercent);
  Serial.print("% | Fuel Litres: ");
  Serial.print(fuelLevel);
  Serial.print(" L | Distance: ");
  Serial.print(distanceKm);
  Serial.print(" KM | Mileage: ");
  Serial.print(mileage);
  Serial.println(" KM/L");
}
`;
}
